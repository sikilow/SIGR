-- Consulta de auditoría (antes: CALL sp_consultar_auditoria(...)).
-- Ejemplo: SELECT * FROM sigr.consultar_auditoria(NULL, NULL, NULL, NULL, 100);
CREATE FUNCTION sigr.consultar_auditoria(
  p_actor_id INT, p_tabla TEXT, p_desde TIMESTAMP, p_hasta TIMESTAMP, p_limite INT
) RETURNS SETOF sigr.sigr_auditoria LANGUAGE sql STABLE AS $$
  SELECT *
    FROM sigr.sigr_auditoria
   WHERE (p_actor_id IS NULL OR actor_id = p_actor_id)
     AND (p_tabla IS NULL OR tabla = p_tabla)
     AND (p_desde IS NULL OR creado_en >= p_desde)
     AND (p_hasta IS NULL OR creado_en < p_hasta)
   ORDER BY id DESC
   LIMIT LEAST(GREATEST(COALESCE(p_limite, 100), 1), 500);
$$;

