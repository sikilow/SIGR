-- =====================================================================
-- ACCESO: nadie fuera del backend
-- El backend se conecta como el dueño de las tablas (postgres), que no está sujeto a RLS.
-- Las claves públicas de Supabase (anon, authenticated) no tienen acceso al esquema
-- y, por si alguien las expone después, RLS sin políticas les niega todas las filas.
-- =====================================================================
DO $$
DECLARE
  v_tabla TEXT;
BEGIN
  FOR v_tabla IN SELECT tablename FROM pg_tables WHERE schemaname = 'sigr' LOOP
    EXECUTE format('ALTER TABLE sigr.%I ENABLE ROW LEVEL SECURITY', v_tabla);
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON SCHEMA sigr FROM anon;
    REVOKE ALL ON ALL TABLES IN SCHEMA sigr FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON SCHEMA sigr FROM authenticated;
    REVOKE ALL ON ALL TABLES IN SCHEMA sigr FROM authenticated;
  END IF;
END;
$$;
