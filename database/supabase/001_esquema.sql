  id_notificacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_reservacion INT NOT NULL,
  tipo VARCHAR(20) COLLATE sigr.es_ci NOT NULL,
  evento VARCHAR(20) COLLATE sigr.es_ci NOT NULL DEFAULT '',
  destinatario VARCHAR(120) COLLATE sigr.es_ci NOT NULL,
  estado VARCHAR(20) COLLATE sigr.es_ci NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'enviada')),
