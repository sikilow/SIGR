-- =====================================================================
-- SIGR · La Madalena — ESQUEMA PARA POSTGRESQL (Supabase)
-- Equivale a database/init.sql + migraciones MySQL 001 a 017 aplicadas.
-- No se ejecuta a mano: lo aplica `npm run db:migrar` (backend/src/utils/migrar.ts),
-- que también fija la zona horaria de la base y registra el archivo en sigr.migracion.
--
-- Diferencias deliberadas con MySQL:
--  * Las tablas viven en el esquema `sigr`, que la API pública de Supabase no expone;
--    además tienen RLS activado y sin políticas, así que las claves anon/authenticated no las ven.
--  * El texto usa la collation `sigr.es_ci` (sin distinguir mayúsculas ni acentos), igual que
--    utf8mb4_unicode_ci: "cajero" = "Cajero" y "Salon" = "Salón" en búsquedas y en UNIQUE.
--  * DATETIME → TIMESTAMP(0) sin zona: guarda la hora local del restaurante, como MySQL.
--  * La auditoría usa una sola función genérica (sigr.fn_auditar) en lugar de 3 triggers por tabla.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS sigr;
SET search_path TO sigr, public;

-- Comparación sin mayúsculas ni acentos (nivel 1 de ICU), como utf8mb4_unicode_ci.
CREATE COLLATION IF NOT EXISTS sigr.es_ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);

-- Búsqueda por subcadena sin mayúsculas ni acentos (antes LOCATE con utf8mb4_unicode_ci).
-- PostgreSQL no permite buscar subcadenas con una collation no determinista, por eso se normaliza el texto.
CREATE FUNCTION sigr.contiene(p_texto TEXT, p_busqueda TEXT) RETURNS BOOLEAN
LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT strpos(
    translate(lower(p_texto COLLATE "und-x-icu"), 'áàäâãéèëêíìïîóòöôõúùüûñç', 'aaaaaeeeeiiiiooooouuuunc') COLLATE "C",
    translate(lower(p_busqueda COLLATE "und-x-icu"), 'áàäâãéèëêíìïîóòöôõúùüûñç', 'aaaaaeeeeiiiiooooouuuunc') COLLATE "C"
  ) > 0
$$;

