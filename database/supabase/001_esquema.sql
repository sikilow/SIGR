CREATE VIEW vista_ventas_detalle AS
SELECT v.id_venta, v.fecha_hora, v.total, u.nombre AS cajero, m.numero AS numero_mesa
  FROM venta v
  JOIN usuario u ON u.id_usuario = v.id_cajero
  JOIN cuenta c ON c.id_cuenta = v.id_cuenta
  JOIN mesa m ON m.id_mesa = c.id_mesa;

-- configuracion_reservacion.actualizado_en: equivalente a ON UPDATE CURRENT_TIMESTAMP de MySQL.
CREATE FUNCTION sigr.fn_tocar_actualizado_en() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.actualizado_en := LOCALTIMESTAMP(0);
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_configuracion_reservacion_actualizado BEFORE UPDATE ON configuracion_reservacion
  FOR EACH ROW EXECUTE FUNCTION sigr.fn_tocar_actualizado_en();

-- =====================================================================
-- SEGURIDAD: primer gerente protegido (migración MySQL 013)
-- =====================================================================
CREATE TABLE configuracion_seguridad (
  id SMALLINT PRIMARY KEY CHECK (id = 1),
  id_primer_gerente INT NULL,
  CONSTRAINT fk_config_seguridad_primer_gerente FOREIGN KEY (id_primer_gerente)
    REFERENCES usuario (id_usuario) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- El primer usuario con rol Gerente queda registrado como protegido.
CREATE FUNCTION sigr.fn_registrar_primer_gerente() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  UPDATE sigr.configuracion_seguridad
     SET id_primer_gerente = NEW.id_usuario
   WHERE id = 1 AND id_primer_gerente IS NULL
     AND NEW.id_rol = (SELECT id_rol FROM sigr.rol WHERE LOWER(nombre) = 'gerente' LIMIT 1);
  RETURN NULL;
END;
$$;
CREATE TRIGGER trg_usuario_00_primer_gerente AFTER INSERT OR UPDATE ON usuario
  FOR EACH ROW EXECUTE FUNCTION sigr.fn_registrar_primer_gerente();

CREATE FUNCTION sigr.fn_proteger_primer_gerente() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  v_primer_gerente INT;
BEGIN
  SELECT id_primer_gerente INTO v_primer_gerente FROM sigr.configuracion_seguridad WHERE id = 1;
  IF TG_OP = 'DELETE' THEN
    IF OLD.id_usuario = v_primer_gerente THEN
      RAISE EXCEPTION 'El primer gerente no se puede eliminar';
    END IF;
    RETURN OLD;
  END IF;
  IF OLD.id_usuario = v_primer_gerente AND (NEW.activo = FALSE OR NEW.id_rol <> OLD.id_rol) THEN
    RAISE EXCEPTION 'El primer gerente no se puede desactivar ni cambiar de rol';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_usuario_proteger_primer_gerente BEFORE UPDATE OR DELETE ON usuario
  FOR EACH ROW EXECUTE FUNCTION sigr.fn_proteger_primer_gerente();

CREATE FUNCTION sigr.fn_configuracion_seguridad_inmutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'No se puede eliminar la configuracion de seguridad';
  END IF;
  IF OLD.id_primer_gerente IS NOT NULL AND NEW.id_primer_gerente IS DISTINCT FROM OLD.id_primer_gerente THEN
    RAISE EXCEPTION 'El primer gerente protegido no se puede reemplazar';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER trg_config_seguridad_inmutable BEFORE UPDATE OR DELETE ON configuracion_seguridad
  FOR EACH ROW EXECUTE FUNCTION sigr.fn_configuracion_seguridad_inmutable();

-- =====================================================================
-- AUDITORÍA (migración MySQL 013)
-- El backend fija el actor por transacción con set_config('sigr.actor_id', ...).
-- Sin sesión autenticada (tareas automáticas, SQL manual) el actor queda NULL.
-- No se guardan hashes de contraseña ni respuestas idempotentes en las instantáneas,
-- pero campos_modificados sí indica si cambiaron.
-- =====================================================================
CREATE TABLE sigr_auditoria (
  id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  actor_id INT NULL,
  tabla VARCHAR(64) NOT NULL,
  operacion VARCHAR(6) NOT NULL CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE')),
  registro_id JSONB NOT NULL,
  antes JSONB NULL,
  despues JSONB NULL,
  campos_modificados JSONB NULL,
  creado_en TIMESTAMP(6) NOT NULL DEFAULT LOCALTIMESTAMP,
  usuario_bd VARCHAR(288) NOT NULL
);
