-- Argumentos: 1) columnas de la llave primaria, 2) columnas que no se copian a la instantánea.
CREATE FUNCTION sigr.fn_auditar() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  v_claves TEXT[] := TG_ARGV[0]::TEXT[];
  v_ocultas TEXT[] := COALESCE(TG_ARGV[1], '{}')::TEXT[];
  v_antes JSONB;
  v_despues JSONB;
  v_registro JSONB;
  v_cambios JSONB;
BEGIN
  IF TG_OP <> 'INSERT' THEN v_antes := to_jsonb(OLD); END IF;
  IF TG_OP <> 'DELETE' THEN v_despues := to_jsonb(NEW); END IF;

  SELECT jsonb_object_agg(clave, COALESCE(v_despues, v_antes) -> clave)
    INTO v_registro
    FROM unnest(v_claves) AS clave;

  IF TG_OP = 'UPDATE' THEN
    SELECT COALESCE(jsonb_agg(clave ORDER BY clave), '[]'::JSONB)
      INTO v_cambios
      FROM jsonb_object_keys(v_despues) AS clave
     WHERE v_antes -> clave IS DISTINCT FROM v_despues -> clave;
  END IF;

  INSERT INTO sigr.sigr_auditoria (actor_id, tabla, operacion, registro_id, antes, despues, campos_modificados, usuario_bd)
  VALUES (
    NULLIF(current_setting('sigr.actor_id', true), '')::INT,
    TG_TABLE_NAME,
    TG_OP,
    v_registro,
    v_antes - v_ocultas,
    v_despues - v_ocultas,
    v_cambios,
    current_user
  );
  RETURN NULL;
END;
$$;

